CREATE TABLE IF NOT EXISTS settings (id SMALLINT PRIMARY KEY CHECK(id=1), enabled SMALLINT NOT NULL DEFAULT 0, owner_sub TEXT);
INSERT INTO settings(id) VALUES(1) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS users (sub TEXT PRIMARY KEY, email TEXT NOT NULL, active SMALLINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS connections (user_sub TEXT NOT NULL REFERENCES users(sub) ON DELETE CASCADE, id TEXT NOT NULL, fields TEXT NOT NULL, PRIMARY KEY(user_sub,id));
